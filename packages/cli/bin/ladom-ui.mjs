#!/usr/bin/env node
// ladom-ui: copies Ladom UI components, tokens and icons into your project, from the registry at
// https://ui.ladom.co/r. Free components need nothing; Pro components need a license key in
// LADOM_UI_KEY. No dependencies: Node 20 or later.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';

const CONFIG = 'ladom-ui.json';
const DEFAULTS = { registry: 'https://ui.ladom.co/r', dir: 'components/ladom' };

const HELP = `ladom-ui — add Ladom UI to your project

Usage
  npx ladom-ui init [--dir components/ladom]   Set up the folder and copy the tokens
  npx ladom-ui add <name...> [--overwrite]     Copy components (and what they need)
  npx ladom-ui update [name...] [--overwrite]  Bring installed components up to date
  npx ladom-ui diff <name>                     Show how your files differ from the latest
  npx ladom-ui icons <name...>                  Copy extra icons for your own code
  npx ladom-ui list                            List the components, their tier and updates
  npx ladom-ui skill                           Add the Claude Code skill to .claude/skills

Pro components need a license key:  LADOM_UI_KEY=ldm_pro_… npx ladom-ui add accordion
Docs: https://ui.ladom.co/en/docs/installation · License: https://ui.ladom.co/license`;

const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.indexOf(`--${name}`);
  if (i === -1) return undefined;
  const value = args[i + 1];
  args.splice(i, value && !value.startsWith('--') ? 2 : 1);
  return value && !value.startsWith('--') ? value : true;
};
const fail = (message) => {
  console.error(`\x1b[31m✖\x1b[0m ${message}`);
  process.exit(1);
};
const ok = (message) => console.log(`\x1b[32m✔\x1b[0m ${message}`);

const root = process.cwd();
const readConfig = () => (existsSync(join(root, CONFIG)) ? { ...DEFAULTS, ...JSON.parse(readFileSync(join(root, CONFIG), 'utf8')) } : null);
const writeConfig = (config) => writeFileSync(join(root, CONFIG), `${JSON.stringify(config, null, 2)}\n`);
const registryUrl = (config) => (process.env.LADOM_UI_REGISTRY ?? config.registry).replace(/\/$/, '');

async function get(config, file) {
  const headers = { Accept: 'application/json' };
  if (process.env.LADOM_UI_KEY) headers.Authorization = `Bearer ${process.env.LADOM_UI_KEY}`;
  let res;
  try {
    res = await fetch(`${registryUrl(config)}/${file}`, { headers });
  } catch (e) {
    fail(`Could not reach the registry at ${registryUrl(config)} (${e.cause?.code ?? e.message}).`);
  }
  const body = await res.json().catch(() => ({}));
  return { status: res.status, body };
}

const sha = (text) => createHash('sha256').update(text).digest('hex').slice(0, 16);

// A file goes into the project only inside the components folder. config.files keeps the hash of
// every file as the CLI last wrote it: a file that still has that hash is untouched and can be
// replaced with a newer version; a file whose hash differs was changed by the user and is kept
// (unless overwrite).
function writeInto(config, dir, path, content, overwrite, report) {
  const target = resolve(dir, path);
  if (relative(dir, target).startsWith('..')) fail(`Refusing to write outside ${dir}: ${path}`);
  const key = relative(resolve(root, config.dir), target);
  const files = (config.files ??= {});
  if (existsSync(target)) {
    const current = readFileSync(target, 'utf8');
    if (current === content) {
      files[key] = sha(content);
      return;
    }
    if (!overwrite && files[key] !== sha(current)) {
      report.skipped.push(relative(root, target));
      return;
    }
    report.updated.push(relative(root, target));
  } else report.written.push(relative(root, target));
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content);
  files[key] = sha(content);
}

// <dir>/index.ts re-exports every installed module; <dir>/icons/index.ts every icon file.
function writeIndexes(dir) {
  const iconsDir = join(dir, 'icons');
  if (existsSync(iconsDir)) {
    const icons = readdirSync(iconsDir).filter((f) => /^Icon.*\.ts$/.test(f)).sort();
    writeFileSync(
      join(iconsDir, 'index.ts'),
      `// Generated by ladom-ui. Do not edit.\nexport { createIcon, type IconNode, type IconProps } from './createIcon';\n${icons.map((f) => `export * from './${f.replace(/\.ts$/, '')}';`).join('\n')}\n`,
    );
  }
  const modules = readdirSync(dir)
    .filter((f) => !['icons', 'tokens'].includes(f) && statSync(join(dir, f)).isDirectory())
    .sort()
    .flatMap((folder) => readdirSync(join(dir, folder)).filter((f) => /\.tsx?$/.test(f) && !f.endsWith('.d.ts')).sort().map((f) => `./${folder}/${f.replace(/\.tsx?$/, '')}`));
  if (existsSync(iconsDir)) modules.push('./icons');
  writeFileSync(join(dir, 'index.ts'), `// Generated by ladom-ui. Do not edit.\n${modules.map((m) => `export * from '${m}';`).join('\n')}\n`);
}

async function add(names, { overwrite = false, quietTokens = false, updating = false } = {}) {
  let config = readConfig();
  if (!config) {
    config = { ...DEFAULTS, installed: {} };
    writeConfig(config);
    ok(`Created ${CONFIG} (components go to ${config.dir}).`);
  }
  const dir = resolve(root, config.dir);
  const { status, body: index } = await get(config, 'index.json');
  if (status !== 200) fail(`The registry answered ${status} for its index.`);
  const known = Object.fromEntries(index.items.map((i) => [i.name, i]));
  const unknown = names.filter((n) => !known[n]);
  if (unknown.length) fail(`Unknown component${unknown.length > 1 ? 's' : ''}: ${unknown.join(', ')}. Run "npx ladom-ui list".`);

  // Everything the request needs, dependencies first.
  const order = [];
  const visit = (name) => {
    if (order.includes(name)) return;
    for (const d of known[name].dependencies) visit(d);
    order.push(name);
  };
  names.forEach(visit);
  const pro = order.filter((n) => known[n].tier === 'pro');
  if (pro.length && !process.env.LADOM_UI_KEY) fail(`${pro.join(', ')} ${pro.length > 1 ? 'are' : 'is'} Ladom UI Pro. Set LADOM_UI_KEY to your license key (https://ui.ladom.co/license).`);

  // Fetch everything before writing anything.
  const items = [];
  for (const name of order) {
    const { status: s, body } = await get(config, `${name}.json`);
    if (s === 401) fail(body.error ?? `Your license key was not accepted for "${name}".`);
    if (s !== 200) fail(`The registry answered ${s} for "${name}".`);
    items.push(body);
  }
  const iconNames = new Set(items.flatMap((i) => i.icons));
  const icons = iconNames.size ? (await get(config, 'icons.json')).body.icons : {};

  const report = { written: [], updated: [], skipped: [] };
  for (const item of items) for (const f of item.files) writeInto(config, dir, f.path, f.content, overwrite, report);
  // The icons the items use, plus (on update) every icon already in the project.
  const iconsDir = join(dir, 'icons');
  if (updating && existsSync(iconsDir)) for (const f of readdirSync(iconsDir)) if (/^Icon.*\.ts$/.test(f)) iconNames.add(f.replace(/\.ts$/, ''));
  if (iconNames.size) {
    const all = icons.createIcon ? icons : (await get(config, 'icons.json')).body.icons;
    writeInto(config, dir, 'icons/createIcon.tsx', all.createIcon, overwrite, report);
    for (const name of [...iconNames].sort()) if (all[name]) writeInto(config, dir, `icons/${name}.ts`, all[name], overwrite, report);
  }
  writeIndexes(dir);
  const before = { ...(config.installed ?? {}) };
  // A file the user kept leaves its item out of date, so update offers it again.
  const keptIn = (item) => item.files.some((f) => report.skipped.includes(relative(root, resolve(dir, f.path))));
  config.installed = { ...config.installed, ...Object.fromEntries(items.map((i) => [i.name, keptIn(i) ? (before[i.name] ?? 'changed') : i.hash])) };
  writeConfig(config);

  if (updating) {
    const changed = items.filter((i) => i.files.some((f) => report.updated.includes(relative(root, resolve(dir, f.path))) || report.written.includes(relative(root, resolve(dir, f.path)))));
    if (changed.length) ok(`Updated ${changed.map((i) => i.name).join(', ')} (${report.updated.length + report.written.length} file${report.updated.length + report.written.length > 1 ? 's' : ''}).`);
    else if (!report.skipped.length) ok('Everything is up to date.');
  } else {
    const shown = items.filter((i) => (i.type === 'component' || (i.type === 'tokens' && !quietTokens)) && (names.includes(i.name) || !before[i.name])).map((i) => `${i.name}${i.tier === 'pro' ? ' (Pro)' : ''}`);
    if (shown.length) ok(`Added ${shown.join(', ')} to ${config.dir}.`);
    if (report.updated.length) console.log(`  Updated ${report.updated.length} file${report.updated.length > 1 ? 's' : ''} you had not changed.`);
  }
  if (report.skipped.length)
    console.log(`  Kept ${report.skipped.length} file${report.skipped.length > 1 ? 's' : ''} you changed: ${report.skipped.join(', ')}\n  See the differences with "npx ladom-ui diff <name>"; replace them with --overwrite.`);
  if (!updating) console.log(`  Import from "${config.dir.startsWith('.') ? config.dir : `@/${config.dir}`}" (or a relative path).`);
}

// A small line diff (longest common subsequence) with two lines of context around each change.
function diffLines(a, b) {
  const x = a.split('\n');
  const y = b.split('\n');
  const n = x.length;
  const m = y.length;
  const lcs = Array.from({ length: n + 1 }, () => new Uint16Array(m + 1));
  for (let i = n - 1; i >= 0; i--) for (let j = m - 1; j >= 0; j--) lcs[i][j] = x[i] === y[j] ? lcs[i + 1][j + 1] + 1 : Math.max(lcs[i + 1][j], lcs[i][j + 1]);
  const ops = [];
  let i = 0;
  let j = 0;
  while (i < n || j < m) {
    if (i < n && j < m && x[i] === y[j]) (ops.push([' ', x[i]]), i++, j++);
    else if (i < n && (j === m || lcs[i + 1][j] >= lcs[i][j + 1])) (ops.push(['-', x[i]]), i++);
    else (ops.push(['+', y[j]]), j++);
  }
  const keep = ops.map((_, k) => ops.slice(Math.max(0, k - 2), k + 3).some(([op]) => op !== ' '));
  const out = [];
  ops.forEach(([op, line], k) => {
    if (!keep[k]) {
      if (out[out.length - 1] !== '  …') out.push('  …');
      return;
    }
    out.push(op === '+' ? `\x1b[32m+ ${line}\x1b[0m` : op === '-' ? `\x1b[31m- ${line}\x1b[0m` : `  ${line}`);
  });
  return out.join('\n');
}

const command = args.shift();
const overwrite = flag('overwrite') === true;
if (!command || command === '--help' || command === '-h' || command === 'help') {
  console.log(HELP);
} else if (command === 'init') {
  const dir = flag('dir');
  const registry = flag('registry');
  const config = { ...DEFAULTS, ...(readConfig() ?? {}), ...(typeof dir === 'string' ? { dir } : {}), ...(typeof registry === 'string' ? { registry } : {}), installed: readConfig()?.installed ?? {} };
  writeConfig(config);
  ok(`Wrote ${CONFIG}.`);
  await add(['tokens'], { overwrite });
  console.log(`
Next:
  1. Import the tokens once, at the root of your app:   import '@/${config.dir}/tokens/index.css';
  2. Load Hanken Grotesk as --font-hanken-grotesk on <html> (next/font: variable: '--font-hanken-grotesk').
  3. Add components:                                    npx ladom-ui add button input`);
} else if (command === 'add') {
  if (!args.length) fail('Name the components to add, e.g. "npx ladom-ui add button input".');
  await add(args, { overwrite, quietTokens: true });
} else if (command === 'update') {
  // Everything installed (or the named items) that the registry has a newer version of.
  const config = readConfig();
  if (!config) fail('Run "npx ladom-ui init" first.');
  const { status, body: index } = await get(config, 'index.json');
  if (status !== 200) fail(`The registry answered ${status} for its index.`);
  const installed = config.installed ?? {};
  const unknown = args.filter((n) => !installed[n]);
  if (unknown.length) fail(`Not installed: ${unknown.join(', ')}. Add ${unknown.length > 1 ? 'them' : 'it'} with "npx ladom-ui add".`);
  const names = args.length ? args : Object.keys(installed);
  const outdated = overwrite || args.length ? names : names.filter((n) => index.items.find((i) => i.name === n)?.hash !== installed[n]);
  await add(outdated.length ? outdated : ['tokens'], { overwrite, updating: true });
} else if (command === 'diff') {
  // How the project's files differ from the registry's latest version of an item.
  const config = readConfig();
  if (!config) fail('Run "npx ladom-ui init" first.');
  if (args.length !== 1) fail('Name one component, e.g. "npx ladom-ui diff button".');
  const { status, body: item } = await get(config, `${args[0]}.json`);
  if (status === 401) fail(item.error);
  if (status !== 200) fail(`The registry answered ${status} for "${args[0]}".`);
  const dir = resolve(root, config.dir);
  let same = true;
  for (const f of item.files) {
    const target = resolve(dir, f.path);
    const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (current === f.content) continue;
    same = false;
    console.log(`\n\x1b[1m${relative(root, target)}\x1b[0m ${current ? '' : '(missing)'}\n${diffLines(current, f.content)}`);
  }
  if (same) ok(`${args[0]} matches the latest version.`);
  else console.log(`\n  - your file   + latest version\n  Take the latest with "npx ladom-ui update ${args[0]} --overwrite".`);
} else if (command === 'icons') {
  // Extra icons for your own code: npx ladom-ui icons IconAdd IconShare (or add, share).
  const config = readConfig();
  if (!config) fail('Run "npx ladom-ui init" first.');
  const { status, body } = await get(config, 'icons.json');
  if (status !== 200) fail(`The registry answered ${status} for the icons.`);
  const wanted = args.map((a) => (a.startsWith('Icon') ? a : `Icon${a.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase())}`));
  const missing = wanted.filter((n) => !body.icons[n]);
  if (!args.length || missing.length) fail(args.length ? `Unknown icon${missing.length > 1 ? 's' : ''}: ${missing.join(', ')}. Browse them at https://ui.ladom.co/en/docs/foundations/icons.` : 'Name the icons, e.g. "npx ladom-ui icons add share".');
  const dir = resolve(root, config.dir);
  const report = { written: [], updated: [], skipped: [] };
  writeInto(config, dir, 'icons/createIcon.tsx', body.icons.createIcon, overwrite, report);
  for (const n of wanted) writeInto(config, dir, `icons/${n}.ts`, body.icons[n], overwrite, report);
  writeIndexes(dir);
  writeConfig(config);
  ok(`Added ${wanted.join(', ')} to ${config.dir}/icons.`);
} else if (command === 'skill') {
  // The Claude Code skill that teaches Claude the components and the rules.
  const { status, body } = await get(readConfig() ?? DEFAULTS, 'skill.json');
  if (status !== 200) fail(`The registry answered ${status} for the skill.`);
  const report = { written: [], updated: [], skipped: [] };
  // Tracked with the component files, by its path from the project root.
  const config = readConfig();
  const tracking = { dir: '.', files: (config?.files ?? {}) };
  writeInto(tracking, root, body.path, body.content, overwrite, report);
  if (config) writeConfig({ ...config, files: tracking.files });
  if (report.skipped.length) console.log(`  Kept your changed ${body.path}; use --overwrite to replace it.`);
  else ok(report.written.length ? `Added the Claude Code skill to ${body.path}.` : report.updated.length ? `Updated ${body.path}.` : `${body.path} is up to date.`);
} else if (command === 'list') {
  const config = readConfig() ?? DEFAULTS;
  const { status, body } = await get(config, 'index.json');
  if (status !== 200) fail(`The registry answered ${status}.`);
  const installed = config.installed ?? {};
  for (const tier of ['free', 'pro']) {
    console.log(`\n${tier === 'free' ? 'Free' : 'Pro (needs LADOM_UI_KEY)'}`);
    for (const i of body.items.filter((x) => x.type === 'component' && x.tier === tier))
      console.log(`  ${installed[i.name] ? '●' : '○'} ${i.name.padEnd(14)} ${i.description}${installed[i.name] && installed[i.name] !== i.hash ? '  \x1b[33m(update available)\x1b[0m' : ''}`);
  }
  console.log('');
} else {
  fail(`Unknown command "${command}". Run "npx ladom-ui --help".`);
}
