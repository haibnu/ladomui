// Generates the React icon components from icons.json:
//   tabler icons  -> node data from @tabler/icons (tabler-nodes-outline/filled.json)
//   figma icons   -> figma/svg/<name>.svg, flattened to plain shapes painted with currentColor
// Pending icons are skipped. Writes src/icons/*.ts, src/index.ts and src/all.ts.
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const readJson = async (path) => JSON.parse(await readFile(new URL(path, root), 'utf8'));
const mapping = await readJson('icons.json');
// Read by path: the package's export map does not expose these files.
const tabler = {
  outline: await readJson('node_modules/@tabler/icons/tabler-nodes-outline.json'),
  filled: await readJson('node_modules/@tabler/icons/tabler-nodes-filled.json'),
};

const camel = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const componentName = (name) => `Icon${name.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('')}`;
const camelAttrs = (attrs) => Object.fromEntries(Object.entries(attrs).map(([k, v]) => [camel(k), String(v)]));

// Figma exports one solid color (the high-emphasis text color) inside a clip-path group.
// Keep the shapes and their geometry attributes; paint comes from currentColor.
const FIGMA_DROP = new Set(['fill', 'fill-opacity', 'clip-path']);
function figmaNode(name, svg) {
  const body = svg.replace(/<defs>[\s\S]*?<\/defs>/, '').replace(/<\/?svg[^>]*>/g, '');
  const errors = [];
  for (const g of body.match(/<g\b[^>]*>/g) ?? []) {
    if (g.replace(/\s*clip-path="[^"]*"/, '') !== '<g>') errors.push(`unexpected group ${g}`);
  }
  const nodes = [];
  for (const [, tag, rawAttrs] of body.matchAll(/<(path|rect|circle|ellipse|polygon|polyline|line)\b([^>]*?)\/?>/g)) {
    const attrs = Object.fromEntries([...rawAttrs.matchAll(/([\w:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
    if (attrs.fill && !/^#1a1711$/i.test(attrs.fill)) errors.push(`unexpected fill ${attrs.fill}`);
    if (attrs.stroke) errors.push(`unexpected stroke ${attrs.stroke}`);
    nodes.push([tag, camelAttrs(Object.fromEntries(Object.entries(attrs).filter(([k]) => !FIGMA_DROP.has(k))))]);
  }
  if (!nodes.length) errors.push('no shapes');
  if (errors.length) throw new Error(`figma/svg/${name}.svg: ${errors.join('; ')}`);
  return nodes;
}

const icons = [];
for (const [name, entry] of Object.entries(mapping)) {
  if (entry.pending) continue;
  let style, node;
  if (entry.source === 'figma') {
    style = 'fill';
    node = figmaNode(name, await readFile(new URL(`figma/svg/${name}.svg`, root), 'utf8'));
  } else {
    const set = entry.style === 'filled' ? 'filled' : 'outline';
    const raw = tabler[set][entry.tabler];
    if (!raw) throw new Error(`${name}: Tabler has no ${set} icon "${entry.tabler}"`);
    style = set === 'filled' ? 'fill' : 'outline';
    node = raw.map(([tag, attrs]) => [tag, camelAttrs(attrs)]);
  }
  icons.push({ name, component: componentName(name), style, node, entry });
}

const dupes = icons.filter((i, n) => icons.findIndex((j) => j.component === i.component) !== n);
if (dupes.length) throw new Error(`Duplicate component names: ${dupes.map((d) => d.component).join(', ')}`);

const header = '// Generated by scripts/build.mjs from icons.json. Do not edit.\n';
const dir = new URL('src/icons/', root);
await rm(dir, { recursive: true, force: true });
await mkdir(dir, { recursive: true });
for (const i of icons) {
  await writeFile(
    new URL(`${i.component}.ts`, dir),
    `${header}import { createIcon } from '../createIcon';\n\nexport const ${i.component} = /* @__PURE__ */ createIcon('${i.component}', '${i.style}', ${JSON.stringify(i.node)});\n`,
  );
}

await writeFile(
  new URL('src/index.ts', root),
  `${header}export { createIcon, type IconNode, type IconProps } from './createIcon';\n\n` +
    icons.map((i) => `export { ${i.component} } from './icons/${i.component}';`).join('\n') +
    `\n\nexport const iconNames = ${JSON.stringify(icons.map((i) => i.name), null, 2)} as const;\n\nexport type IconName = (typeof iconNames)[number];\n`,
);

// Every icon by name, for galleries and name-based lookups. Importing this pulls in all icons.
await writeFile(
  new URL('src/all.ts', root),
  `${header}import type { IconName } from './index';\n` +
    icons.map((i) => `import { ${i.component} } from './icons/${i.component}';`).join('\n') +
    `\n\nexport const icons = {\n${icons.map((i) => `  '${i.name}': ${i.component},`).join('\n')}\n} as const satisfies Record<IconName, unknown>;\n\n` +
    `export const iconMeta: Record<IconName, { category: string; source: 'tabler' | 'figma'; tabler?: string; figma: string }> = ${JSON.stringify(
      Object.fromEntries(
        icons.map((i) => [i.name, { category: i.entry.category, source: i.entry.source === 'figma' ? 'figma' : 'tabler', ...(i.entry.tabler && { tabler: i.entry.tabler }), figma: i.entry.figma.name }]),
      ),
      null,
      2,
    )};\n`,
);

console.log(`icons: ${icons.length} (${icons.filter((i) => i.entry.source === 'figma').length} from Figma), ${Object.values(mapping).filter((e) => e.pending).length} pending`);
