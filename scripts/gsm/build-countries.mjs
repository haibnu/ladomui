// Builds packages/ui/src/GsmInput/countries.ts: every country libphonenumber knows, with its calling
// code, a national number format taken from its example mobile number (international format,
// so no trunk "0") and its flag from country-flag-icons (MIT, 3x2). TR and US keep the Figma
// format and flags (flags.tsx). Run: node scripts/gsm/build-countries.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const repo = join(dirname(fileURLToPath(import.meta.url)), '../..');
const phone = require('libphonenumber-js/max');
const examples = require('libphonenumber-js/mobile/examples');
const { Metadata } = require('libphonenumber-js/core');
const maxMetadata = require('libphonenumber-js/max/metadata');
const flagDir = join(dirname(require.resolve('country-flag-icons/package.json')), '3x2');
const flagVersion = require('country-flag-icons/package.json').version;
const phoneVersion = require('libphonenumber-js/package.json').version;

// Figma's GSM input (1591:5) draws these two.
const FIGMA = { TR: { format: '(###) ### ## ##', placeholder: '(5XX) XXX XX XX' }, US: { format: '(###) ###-####' } };

const metadata = new Metadata(maxMetadata);
// The main country of each calling code (+1 the US, +44 the UK, +7 Russia), for pasted numbers.
const mainOf = (dial) => maxMetadata.country_calling_codes[dial]?.[0];
const rows = [];
const flags = {};
for (const code of phone.getCountries()) {
  const dial = phone.getCountryCallingCode(code);
  let format = FIGMA[code]?.format;
  let placeholder = FIGMA[code]?.placeholder;
  metadata.selectNumberingPlan(code);
  // Mobile lengths where the plan lists them (a GSM field takes mobile numbers), else the plan's.
  const lengths = metadata.numberingPlan.type('MOBILE')?.possibleLengths() ?? metadata.numberingPlan.possibleLengths();
  if (!format) {
    const example = phone.getExampleNumber(code, examples);
    if (!example) continue;
    format = example.formatInternational().replace(`+${dial}`, '').trim().replace(/\d/g, '#');
  }
  let digits = format.split('').filter((c) => c === '#').length;
  // Room for the longest number of the plan: the extra digits go at the end of the last group.
  const max = Math.max(...lengths);
  if (!FIGMA[code] && max > digits) {
    format += '#'.repeat(max - digits);
    digits = max;
  }
  const min = Math.min(...lengths);
  const row = { code, dial, format };
  if (placeholder) row.placeholder = placeholder;
  if (min < digits) row.minDigits = min;
  if ((maxMetadata.country_calling_codes[dial]?.length ?? 0) > 1 && mainOf(dial) === code) row.primary = true;
  rows.push(row);
  if (!FIGMA[code]) {
    let svg;
    try {
      svg = readFileSync(join(flagDir, `${code}.svg`), 'utf8');
    } catch {
      continue;
    }
    const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
    const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
    flags[code] = [viewBox, body];
  }
}

// Turkey and the US first (Figma's flags); the rest are sorted by name where they are shown.
rows.sort((a, b) => (a.code === 'TR' ? -1 : b.code === 'TR' ? 1 : a.code === 'US' ? -1 : b.code === 'US' ? 1 : a.code.localeCompare(b.code)));

const out = `// Generated by scripts/gsm/build-countries.mjs from libphonenumber-js ${phoneVersion} and
// country-flag-icons ${flagVersion} (both MIT); do not edit. Flags are [viewBox, inner SVG].
import type { Country } from './phoneFormat';

export const COUNTRY_DATA: Country[] = ${JSON.stringify(rows)};

export const FLAG_SVG: Record<string, [string, string]> = ${JSON.stringify(flags)};
`;
writeFileSync(join(repo, 'packages/ui/src/GsmInput/countries.ts'), out);
console.log(`countries.ts: ${rows.length} countries, ${Object.keys(flags).length} flags, ${(out.length / 1024).toFixed(0)} KB`);
